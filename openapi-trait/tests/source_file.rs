use axum_default::petstore::PetstoreApi as _;

#[derive(Clone)]
struct MockPetstore;

impl axum_default::petstore::PetstoreApi for MockPetstore {
    type Error = axum_default::petstore::NotImplemented;
}

#[test]
fn included_axum_module_is_usable() {
    let _router = MockPetstore.router();
    let req = axum_default::petstore::GetPetByIdRequest { pet_id: 42 };
    assert_eq!(req.pet_id, 42);
}

#[test]
fn included_client_module_is_usable() {
    let req = client_dir::petstore::GetPetByIdRequest { pet_id: 7 };
    assert_eq!(req.pet_id, 7);
}

/// Files generated into `dir` whose name starts with `prefix`.
fn generated_files(dir: &std::path::Path, prefix: &str) -> Vec<std::path::PathBuf> {
    std::fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|entry| entry.unwrap().path())
        .filter(|path| {
            path.extension().is_some_and(|ext| ext == "rs")
                && path
                    .file_name()
                    .and_then(|n| n.to_str())
                    .is_some_and(|n| n.starts_with(prefix))
        })
        .collect()
}

fn assert_generated_header(path: &std::path::Path) {
    let text = std::fs::read_to_string(path).unwrap();
    assert!(
        text.starts_with(
            "// @generated by openapi-trait from `assets/testdata/petstore.openapi.yaml`"
        ),
        "{}",
        path.display()
    );
}

#[test]
fn default_location_is_self_ignoring_dir_in_crate() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(".openapi-trait");
    let files = generated_files(&dir, "petstore.axum.");
    assert_eq!(files.len(), 1, "{files:?}");
    assert_generated_header(&files[0]);
    let gitignore = std::fs::read_to_string(dir.join(".gitignore")).unwrap();
    assert!(gitignore.lines().any(|line| line == "*"), "{gitignore}");
}

#[test]
fn explicit_dir_is_relative_to_manifest() {
    let dir =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../target/openapi-trait-test-gen");
    let files = generated_files(&dir, "petstore.client.");
    assert_eq!(files.len(), 1, "{files:?}");
    assert_generated_header(&files[0]);
}
